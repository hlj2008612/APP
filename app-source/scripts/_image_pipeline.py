
import sys, os, json, argparse, struct

MANIFEST_HEADER = "// AUTO-GENERATED by scripts/optimize-images.mjs - DO NOT EDIT BY HAND.\n"

def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument('--src', required=True)
    p.add_argument('--thumb-dir', required=True)
    p.add_argument('--full-dir', required=True)
    p.add_argument('--report-json', required=True)
    p.add_argument('--thumb-edge', type=int, default=560)
    p.add_argument('--thumb-quality', type=int, default=78)
    p.add_argument('--thumb-method', type=int, default=6)
    p.add_argument('--full-edge', type=int, default=1600)
    p.add_argument('--full-quality', type=int, default=80)
    p.add_argument('--full-method', type=int, default=6)
    p.add_argument('--only', default='')  # comma separated ids; empty = all
    return p.parse_args()

def webp_dims(path):
    """Parse the true pixel dimensions straight out of the WebP stream."""
    with open(path, 'rb') as fh:
        head = fh.read(32)
    if head[:4] != b'RIFF' or head[8:12] != b'WEBP':
        raise ValueError('not a RIFF/WEBP file: ' + path)
    fmt = head[12:16]
    if fmt == b'VP8X':
        w = 1 + (head[24] | (head[25] << 8) | (head[26] << 16))
        h = 1 + (head[27] | (head[28] << 8) | (head[29] << 16))
        return w, h
    if fmt == b'VP8 ':
        # lossy: 3-byte sync code, then 14-bit width/height
        off = head.index(b'\x9d\x01\x2a')
        w = struct.unpack('<H', head[off+3:off+5])[0] & 0x3FFF
        h = struct.unpack('<H', head[off+5:off+7])[0] & 0x3FFF
        return w, h
    if fmt == b'VP8L':
        b = head[21:25]
        bits = b[0] | (b[1] << 8) | (b[2] << 16) | (b[3] << 24)
        return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
    raise ValueError('unknown webp chunk ' + repr(fmt))

def fit(size, longest):
    w, h = size
    if max(w, h) <= longest:
        return w, h, False
    if w >= h:
        return longest, max(1, round(h * longest / w)), True
    return max(1, round(w * longest / h)), longest, True

def main():
    a = parse_args()
    from PIL import Image
    Image.MAX_IMAGE_PIXELS = None
    files = sorted([f for f in os.listdir(a.src) if f.lower().endswith('.jpg')],
                   key=lambda f: int(os.path.splitext(f)[0]))
    wanted = set(int(x) for x in a.only.split(',') if x.strip())
    if wanted:
        files = [f for f in files if int(os.path.splitext(f)[0]) in wanted]
    os.makedirs(a.thumb_dir, exist_ok=True)
    os.makedirs(a.full_dir, exist_ok=True)

    records = []
    for name in files:
        idx = int(os.path.splitext(name)[0])
        src = os.path.join(a.src, name)
        row = {'id': idx, 'source': name, 'srcBytes': os.path.getsize(src)}

        with Image.open(src) as im:
            im = __import__('PIL.ImageOps', fromlist=['exif_transpose']).exif_transpose(im)
            if im.mode not in ('RGB', 'RGBA'):
                im = im.convert('RGB')
            row['srcW'], row['srcH'] = im.size

            for tier, outdir, edge, q, meth in (
                ('thumb', a.thumb_dir, a.thumb_edge, a.thumb_quality, a.thumb_method),
                ('full', a.full_dir, a.full_edge, a.full_quality, a.full_method),
            ):
                out = os.path.join(outdir, '%d.webp' % idx)
                tw, th, resized = fit(im.size, edge)
                if resized:
                    work = im.resize((tw, th), Image.LANCZOS)
                else:
                    work = im
                if work.mode == 'RGBA':
                    # WebP keeps alpha, JPEG sources are flattened to RGB above.
                    work.save(out, 'WEBP', quality=q, method=meth, alpha_quality=90)
                else:
                    work.save(out, 'WEBP', quality=q, method=meth)
                    # Re-open to confirm the encoder wrote what we asked for.
                if resized:
                    work.close()
                row['%sW' % tier] = tw
                row['%sH' % tier] = th
                row['%sBytes' % tier] = os.path.getsize(out)
                row['%sResized' % tier] = resized
                row['%sPath' % tier] = out

        # primary truth = the actual on-disk stream, not our in-memory expectation
        row['thumbW'], row['thumbH'] = webp_dims(os.path.join(a.thumb_dir, '%d.webp' % idx))
        row['fullW'], row['fullH'] = webp_dims(os.path.join(a.full_dir, '%d.webp' % idx))
        with Image.open(os.path.join(a.thumb_dir, '%d.webp' % idx)) as t:
            row['thumbPillowDims'] = list(t.size)
        with Image.open(os.path.join(a.full_dir, '%d.webp' % idx)) as t:
            row['fullPillowDims'] = list(t.size)
        records.append(row)
        print('ok %2d  src %dx%d -> thumb %dx%d (%d B)  full %dx%d (%d B)' % (
            idx, row['srcW'], row['srcH'], row['thumbW'], row['thumbH'], row['thumbBytes'],
            row['fullW'], row['fullH'], row['fullBytes']), flush=True)

    with open(a.report_json, 'w', encoding='utf-8') as fh:
        json.dump(records, fh, indent=2)

if __name__ == '__main__':
    main()
